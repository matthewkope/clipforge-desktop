#!/usr/bin/env node
// Registers the ClipForge native messaging host with the Chromium-family
// browsers installed on this Mac, so the extension can reach the desktop app
// without any localhost HTTP server.
//
// What it writes:
//   1. A launcher (~/Library/Application Support/clipforge-desktop/native-host/
//      launch.sh) that runs the host script with an absolute node path and the
//      app's socket path baked in — this avoids the limited PATH the browser
//      gives spawned hosts.
//   2. A host manifest (com.clipforge.host.json) in each browser's
//      NativeMessagingHosts directory, whitelisting the extension ID.
//
// Run with: npm run install:extension-host

import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HOST_NAME = 'com.clipforge.host';
const APP_NAME = 'clipforge-desktop';
const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const home = os.homedir();

const hostScript = path.join(repoRoot, 'extension', 'native-host', 'clipforge-host.mjs');
const idFile = path.join(repoRoot, 'extension', 'native-host', 'extension-id.txt');

if (!existsSync(hostScript)) {
  console.error(`Native host script not found at ${hostScript}`);
  process.exit(1);
}
if (!existsSync(idFile)) {
  console.error(`Extension ID file not found at ${idFile}. Re-run the key generation step.`);
  process.exit(1);
}
const extensionId = readFileSync(idFile, 'utf8').trim();
if (!/^[a-p]{32}$/.test(extensionId)) {
  console.error(`Extension ID "${extensionId}" does not look valid (expected 32 chars a-p).`);
  process.exit(1);
}

const userDataDir = path.join(home, 'Library', 'Application Support', APP_NAME);
const socketPath = path.join(userDataDir, 'clipforge.sock');
const launcherDir = path.join(userDataDir, 'native-host');
const launcherPath = path.join(launcherDir, 'launch.sh');

mkdirSync(launcherDir, { recursive: true });
chmodSync(hostScript, 0o755);

// Absolute node path so the browser-spawned host doesn't depend on PATH.
const nodePath = process.execPath;
const launcher = `#!/bin/bash
# Generated by scripts/install-native-host.mjs — re-run that to update paths.
export CLIPFORGE_SOCKET=${shellQuote(socketPath)}
exec ${shellQuote(nodePath)} ${shellQuote(hostScript)} "$@"
`;
writeFileSync(launcherPath, launcher, 'utf8');
chmodSync(launcherPath, 0o755);

const manifest = {
  name: HOST_NAME,
  description: 'ClipForge native messaging host',
  path: launcherPath,
  type: 'stdio',
  allowed_origins: [`chrome-extension://${extensionId}/`]
};

// macOS user-level NativeMessagingHosts directories, keyed by the browser's
// data-dir root (only install for browsers that are actually present).
const browsers = [
  { name: 'Brave', root: path.join(home, 'Library', 'Application Support', 'BraveSoftware', 'Brave-Browser') },
  { name: 'Chrome', root: path.join(home, 'Library', 'Application Support', 'Google', 'Chrome') },
  { name: 'Chrome Beta', root: path.join(home, 'Library', 'Application Support', 'Google', 'Chrome Beta') },
  { name: 'Chromium', root: path.join(home, 'Library', 'Application Support', 'Chromium') },
  { name: 'Microsoft Edge', root: path.join(home, 'Library', 'Application Support', 'Microsoft Edge') }
];

const installed = [];
for (const browser of browsers) {
  if (!existsSync(browser.root)) {
    continue;
  }
  const nmhDir = path.join(browser.root, 'NativeMessagingHosts');
  mkdirSync(nmhDir, { recursive: true });
  writeFileSync(path.join(nmhDir, `${HOST_NAME}.json`), JSON.stringify(manifest, null, 2), 'utf8');
  installed.push(browser.name);
}

console.log('ClipForge native messaging host installed.');
console.log(`  Extension ID : ${extensionId}`);
console.log(`  Launcher     : ${launcherPath}`);
console.log(`  Socket       : ${socketPath}`);
if (installed.length > 0) {
  console.log(`  Browsers     : ${installed.join(', ')}`);
} else {
  console.log('  Browsers     : none detected — is a Chromium-family browser installed?');
}
console.log('\nNext: reload the unpacked extension (it now has a pinned ID) and restart the browser.');

function shellQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}
